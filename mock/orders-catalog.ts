export function ordersDisplayStatusLabel(status: OrdersDisplayStatus): string {
  const map: Record<OrdersDisplayStatus, string> = {
    processing: "Processing",
    packed: "Packed",
    ready: "Ready",
    in_transit: "In Transit",
    delayed: "Delayed",
    delivered: "Delivered",
    cancelled: "Cancelled",
  };
  return map[status];
}

export function paymentBadgeTone(
  methodId: PaymentMethodId,
): "sky" | "amber" | "violet" | "emerald" | "orange" {
  switch (methodId) {
    case "advance":
      return "sky";
    case "on_loading":
      return "amber";
    case "on_delivery":
      return "violet";
    case "credit_15":
      return "emerald";
    case "credit_30":
      return "orange";
    default:
      return "sky";
  }
}
