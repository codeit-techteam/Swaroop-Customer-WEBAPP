function at(daysAgo: number, hour = 10): string {
  const d = new Date("2026-08-03T12:00:00.000Z");
  d.setUTCDate(d.getUTCDate() - daysAgo);
  d.setUTCHours(hour, 20, 0, 0);
  return d.toISOString();
}

function deliveryIn(days: number): string {
  const d = new Date("2026-08-03T12:00:00.000Z");
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}

function timelineFor(
  status: OrdersDisplayStatus,
  createdAt: string,
): OrderTimelineEvent[] {
  const steps = [
    "Order Created",
    "Order Confirmed",
    "PO Generated",
    "Packed",
    "Dispatched",
    "In Transit",
    "Delivered",
  ] as const;

  const currentIndex: Record<OrdersDisplayStatus, number> = {
    processing: 3,
    packed: 3,
    ready: 4,
    in_transit: 5,
    delayed: 5,
    delivered: 6,
    cancelled: 2,
  };

  const idx = currentIndex[status];
  return steps.map((title, i) => ({
    id: `step-${i}`,
    title,
    status:
      status === "cancelled" && i > idx
        ? "pending"
        : i < idx
          ? "completed"
          : i === idx
            ? status === "cancelled"
              ? "pending"
              : "current"
            : "pending",
    at: i <= idx ? createdAt : null,
  }));
}

function order(
  partial: Omit<OrdersCatalogItem, "timeline"> & {
    timeline?: OrderTimelineEvent[];
  },
): OrdersCatalogItem {
  return {
    ...partial,
    timeline:
      partial.timeline ?? timelineFor(partial.displayStatus, partial.createdAt),
  };
}

