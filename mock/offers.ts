/** Live expiry helpers so countdown timers remain active in the UI. */
const daysFromNow = (days: number, hours = 0, minutes = 0) => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(d.getHours() + hours, d.getMinutes() + minutes, 0, 0);
  return d.toISOString();
};

