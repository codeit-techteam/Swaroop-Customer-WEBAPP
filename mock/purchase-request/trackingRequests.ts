function isoDaysAgo(days: number, hours = 10): string {
  const d = new Date("2026-08-03T12:00:00.000Z");
  d.setUTCDate(d.getUTCDate() - days);
  d.setUTCHours(hours, 15, 0, 0);
  return d.toISOString();
}

function expiryFrom(
  submittedAt: string,
  seconds = PRICE_LOCK_DURATION_SECONDS,
): string {
  return new Date(
    new Date(submittedAt).getTime() + seconds * 1000,
  ).toISOString();
}

