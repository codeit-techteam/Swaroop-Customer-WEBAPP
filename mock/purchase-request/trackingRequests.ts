export function mapSubmittedToTrackingItem(
  submitted: SubmittedPurchaseRequest,
): PurchaseRequestTrackingItem {
  const submittedAt = submitted.createdAt;
  return {
    id: submitted.id,
    displayId: submitted.displayId,
    productId: submitted.product.id,
    productName: submitted.product.name,
    grade: submitted.product.grade,
    quantityMt: submitted.form.quantityMt,
    sellerName: submitted.product.manufacturer,
    warehouse: submitted.product.warehouse,
    createdAt: submittedAt,
    submittedAt,
    approvedAt:
      submitted.status === "approved" ? new Date().toISOString() : null,
    rejectedAt:
      submitted.status === "rejected" ? new Date().toISOString() : null,
    expiredAt: submitted.status === "expired" ? new Date().toISOString() : null,
    paymentMethodId: submitted.paymentMethodId,
    paymentMethodTitle: submitted.paymentMethodTitle,
    status:
      submitted.status === "pending_approval"
        ? "seller_reviewing"
        : submitted.status === "submitted"
          ? "submitted"
          : submitted.status === "approved"
            ? "approved"
            : submitted.status === "rejected"
              ? "rejected"
              : submitted.status === "expired"
                ? "expired"
                : submitted.status === "withdrawn"
                  ? "cancelled"
                  : "submitted",
    requestStatus: submitted.status,
    expectedExpiryAt: expiryFrom(submittedAt),
    secondsRemaining:
      submitted.status === "pending_approval" ||
      submitted.status === "submitted"
        ? PRICE_LOCK_DURATION_SECONDS
        : null,
    orderId: submitted.orderId,
    poNumber: submitted.poNumber,
    orderStatus: submitted.status === "approved" ? "Order Created" : null,
    totalAmount: submitted.summary.grandTotal,
    rejectionReason: null,
    rejectedBy: null,
    canCancel:
      submitted.status === "submitted" ||
      submitted.status === "pending_approval" ||
      submitted.status === "draft",
  };
}

export function formatCountdown(seconds: number): string {
  const safe = Math.max(0, seconds);
  const m = Math.floor(safe / 60);
  const s = safe % 60;
  return `${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}`;
}

export function trackingStatusLabel(status: TrackingListStatus): string {
  const labels: Record<TrackingListStatus, string> = {
    draft: "Draft",
    submitted: "Submitted",
    payment_pending: "Payment Pending",
    review_pending: "Review Pending",
    seller_reviewing: "Under Review",
    pending_approval: "Pending Approval",
    approved: "Approved",
    rejected: "Rejected",
    expired: "Expired",
    cancelled: "Cancelled",
    completed: "Completed",
    archived: "Archived",
    withdrawn: "Withdrawn",
  };
  return labels[status];
}
