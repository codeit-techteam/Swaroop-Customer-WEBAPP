export function getMaterialTaxonomyBySlug(
  slug: string,
): MaterialTaxonomyItem | undefined {
  return materialsTaxonomy.find((item) => item.slug === slug);
}

export function getMaterialTaxonomyByCode(
  code: string,
): MaterialTaxonomyItem | undefined {
  return materialsTaxonomy.find(
    (item) => item.code.toLowerCase() === code.toLowerCase(),
  );
}

export function getMaterialsByParentGroup(
  parentGroup: MaterialParentGroup | string,
): MaterialTaxonomyItem[] {
  return materialsTaxonomy.filter((item) => item.parentGroup === parentGroup);
}
